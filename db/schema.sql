-- JobTrail HK database schema (fresh install)
-- Usage: psql -d jobtrail_hk -f db/schema.sql

CREATE TABLE IF NOT EXISTS jobs (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       TEXT NOT NULL,
    company     TEXT NOT NULL,
    url         TEXT,
    location    TEXT,
    salary      TEXT,
    status      TEXT NOT NULL DEFAULT 'saved',
    source      TEXT,
    notes       TEXT,
    applied_at  DATE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT jobs_status_check CHECK (
        status IN ('saved', 'applied', 'interview', 'offer', 'rejected', 'closed')
    )
);

-- Exact URL duplicates are blocked (blank / null URLs are allowed more than once).
CREATE UNIQUE INDEX IF NOT EXISTS jobs_url_unique
    ON jobs (url)
    WHERE url IS NOT NULL AND btrim(url) <> '';

CREATE INDEX IF NOT EXISTS jobs_status_idx ON jobs (status);
CREATE INDEX IF NOT EXISTS jobs_created_at_idx ON jobs (created_at DESC);
